#!/usr/bin/env python3
"""
BandUp — turn your Google Sheet exports into a SQL file for Supabase.

HOW TO USE
  1. In Google Sheets, for each tab you want to keep:  File → Download → Comma-separated values (.csv)
     Name them exactly:   Candidates.csv  Scores.csv  TestSets.csv  AnswerKeys.csv  Settings.csv
     (any you don't have can simply be left out)
  2. Put them in one folder together with this script, then run:
        python3 import_from_sheets.py
  3. Open the generated  import_data.sql , paste it into Supabase → SQL Editor → Run.
     (If it is very large, run it in several parts — it is plain INSERT statements.)

  • Student passwords are carried over as-is: the old hashes still work, and each student's
    password is upgraded to strong bcrypt automatically the first time they log in.
  • Re-running the SQL is safe (existing rows are skipped / updated, never duplicated).
  • Drafts and OTP codes are not migrated (they are temporary).
"""
import csv, json, os, re, sys
from datetime import datetime

def q(v):
    if v is None: return 'null'
    return "'" + str(v).replace("'", "''") + "'"
def qs(v):                       # text, '' when empty
    return q('' if v is None else str(v))
def ts(v):
    v = (v or '').strip()
    if not v: return 'null'
    for f in ('%Y-%m-%dT%H:%M:%S.%fZ', '%Y-%m-%dT%H:%M:%SZ', '%Y-%m-%d %H:%M:%S', '%m/%d/%Y %H:%M:%S', '%Y-%m-%d'):
        try: return q(datetime.strptime(v, f).strftime('%Y-%m-%d %H:%M:%S') + '+00')
        except ValueError: pass
    return q(v)                  # let Postgres try to parse it
def num(v):
    v = (v or '').strip()
    if v == '': return 'null'
    try: float(v); return v
    except ValueError: return 'null'
def jsonb(v):
    v = (v or '').strip() or '{}'
    try: json.loads(v)
    except Exception: v = '{}'
    return q(v) + '::jsonb'

def rows(name):
    path = name + '.csv'
    if not os.path.exists(path): print(f'  - {path} not found, skipping'); return []
    with open(path, newline='', encoding='utf-8-sig') as f:
        r = list(csv.DictReader(f)); print(f'  ✓ {path}: {len(r)} rows'); return r

out = ['-- Generated by import_from_sheets.py', 'begin;']

for r in rows('Candidates'):
    cid = (r.get('CandidateID') or '').strip().upper()
    if not cid: continue
    status = (r.get('Status') or '').strip() or 'Approved'        # blank = pre-approval-era account → approved
    if status not in ('Pending', 'Approved', 'Rejected'): status = 'Approved'
    out.append(
        "insert into app.candidates(candidate_id,full_name,dob,gender,nationality,email,password_hash,created_at,last_login,photo_base64,status) values "
        f"({q(cid)},{qs(r.get('FullName'))},{qs(r.get('DateOfBirth'))},{qs(r.get('Gender'))},{qs(r.get('Nationality'))},"
        f"{q((r.get('Email') or '').strip().lower())},{qs(r.get('Password'))},coalesce({ts(r.get('CreatedAt'))}::timestamptz,now()),"
        f"{ts(r.get('LastLogin'))}::timestamptz,{qs(r.get('PhotoBase64'))},{q(status)}) on conflict (candidate_id) do nothing;")

for r in rows('TestSets'):
    sid = (r.get('SetID') or '').strip()
    if not sid: continue
    out.append(
        "insert into app.test_sets(set_id,set_name,config_url,status,created_at,description,exam_type) values "
        f"({q(sid)},{qs(r.get('SetName'))},{qs(r.get('ConfigURL'))},{q((r.get('Status') or 'Active').strip())},"
        f"coalesce({ts(r.get('CreatedAt'))}::timestamptz,now()),{qs(r.get('Description'))},{q((r.get('ExamType') or 'IELTS').strip().upper())}) "
        "on conflict (set_id) do nothing;")

for r in rows('AnswerKeys'):
    sid = (r.get('TestSetID') or '').strip()
    if not sid: continue
    out.append(
        "insert into app.answer_keys(test_set_id,listening_key,reading_key,updated_at,updated_by) values "
        f"({q(sid)},{jsonb(r.get('ListeningKey'))},{jsonb(r.get('ReadingKey'))},coalesce({ts(r.get('UpdatedAt'))}::timestamptz,now()),{qs(r.get('UpdatedBy'))}) "
        "on conflict (test_set_id) do update set listening_key=excluded.listening_key, reading_key=excluded.reading_key;")

for r in rows('Scores'):
    sub = (r.get('SubmissionID') or '').strip()
    if not sub: continue
    out.append(
        "insert into app.scores(submission_id,ts,candidate_id,full_name,test_set_id,test_set_name,listening_score,listening_band,reading_score,reading_band,"
        "writing_t1_band,writing_t2_band,writing_band,speaking_band,overall_band,writing_t1_wc,writing_t2_wc,writing_t1_text,writing_t2_text,examiner_notes,"
        "graded_by,graded_at,listening_answers,reading_answers,exam_type,listening_scaled,reading_scaled,toeic_total) values "
        f"({q(sub)},coalesce({ts(r.get('Timestamp'))}::timestamptz,now()),{q((r.get('CandidateID') or '').strip().upper())},{qs(r.get('FullName'))},"
        f"{qs(r.get('TestSetID'))},{qs(r.get('TestSetName'))},{num(r.get('ListeningScore'))},{num(r.get('ListeningBand'))},{num(r.get('ReadingScore'))},{num(r.get('ReadingBand'))},"
        f"{num(r.get('WritingTask1Band'))},{num(r.get('WritingTask2Band'))},{num(r.get('WritingBand'))},{num(r.get('SpeakingBand'))},{num(r.get('OverallBand'))},"
        f"coalesce({num(r.get('WritingTask1WC'))},0),coalesce({num(r.get('WritingTask2WC'))},0),{qs(r.get('WritingTask1Text'))},{qs(r.get('WritingTask2Text'))},"
        f"{qs(r.get('ExaminerNotes'))},{qs(r.get('GradedBy'))},{ts(r.get('GradedAt'))}::timestamptz,{qs(r.get('ListeningAnswers'))},{qs(r.get('ReadingAnswers'))},"
        f"{q((r.get('ExamType') or 'IELTS').strip().upper())},{num(r.get('ListeningScaled'))},{num(r.get('ReadingScaled'))},{num(r.get('TOEICTotal'))}) "
        "on conflict (submission_id) do nothing;")

for r in rows('Settings'):
    k = (r.get('Key') or '').strip()
    if k in ('institution_name', 'institution_address', 'trf_footer_note', 'notify_email', 'active_set_id'):
        out.append(f"select app.set_setting({q(k)},{qs(r.get('Value'))});")
    # admin_password is intentionally NOT imported — set a new one with app.set_admin_password()

out.append('commit;')
with open('import_data.sql', 'w', encoding='utf-8') as f: f.write('\n'.join(out) + '\n')
print(f'\nWrote import_data.sql  ({len(out) - 2} statements)')
